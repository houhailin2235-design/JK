 const address=await owner.getAddress();const a=await asset.getAddress();const m=await middle.getAddress();const r1=await first.getAddress();const r2=await second.getAddress();
 const executor=await deploy('AtomicArbitrage.sol','AtomicArbitrage',[address,a,r1,r2,parseEther('100')]);const target=await executor.getAddress();
 for(const [token,to,value] of [[asset,address,'1000'],[asset,r2,'10000'],[middle,r1,'10000'],[asset,target,'10'],[middle,target,'5']])await(await token.mint(to,parseEther(value))).wait();
