import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const dir=path.dirname(fileURLToPath(import.meta.url));
const lab=process.env.ARB_TEST_LAB||'D:/新建文件夹/新建文件夹/.codex-storage/temp/arb-executor-lab';
const require=createRequire(path.join(lab,'package.json'));
const solc=require('solc');
const ganache=require('ganache');
const {BrowserProvider,ContractFactory,parseEther}=require('ethers');
const sources=Object.fromEntries(['AtomicArbitrage.sol','TestFixtures.sol'].map(name=>[name,{content:fs.readFileSync(path.join(dir,name),'utf8')} ]));
const output=JSON.parse(solc.compile(JSON.stringify({language:'Solidity',sources,settings:{optimizer:{enabled:true,runs:200},evmVersion:'shanghai',outputSelection:{'*':{'*':['abi','evm.bytecode.object','evm.deployedBytecode.object']}}}}),{import(name){try{return {contents:fs.readFileSync(path.join(lab,'node_modules',name),'utf8')}}catch{return {error:'Missing import: '+name}}}}));
